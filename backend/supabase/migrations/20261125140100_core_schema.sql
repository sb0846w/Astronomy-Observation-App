-- =====================================================================
-- AstroLog core schema
--
--   auth.users 1──1 profiles 1──< observing_sessions 1──< celestial_observations
--
-- * Primary keys of sessions and observations are UUIDs generated on the phone,
--   so re-uploading the same record updates it instead of creating a duplicate.
-- * celestial_observations references observing_sessions through (session_id, user_id),
--   so an observation can never belong to a different user than its session.
-- * Optional text fields are stored as NULL (never as empty strings).
-- =====================================================================

create extension if not exists pg_trgm with schema extensions;

-- Helper functions that must never be callable through the REST API live here
-- (only the "public" schema is exposed by Supabase's Data API).
create schema if not exists private;
revoke all on schema private from public;

-- ---------------------------------------------------------------- profiles

create table public.profiles (
  id            uuid primary key references auth.users (id) on delete cascade,
  display_name  text check (display_name is null or char_length(btrim(display_name)) between 1 and 80),
  email         text,                      -- NULL for anonymous users
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);

comment on table public.profiles is
  'One row per Supabase Auth user (including anonymous users). Created automatically by a trigger.';

-- ---------------------------------------------------------------- observing_sessions

create table public.observing_sessions (
  id                  uuid primary key,    -- generated by the Android app (ObservingSession.cloudId)
  user_id             uuid not null default auth.uid()
                        references public.profiles (id) on delete cascade,

  -- required coursework fields
  session_title       text not null check (char_length(btrim(session_title)) between 1 and 120),
  session_date        date not null,
  session_time        text not null check (session_time ~ '^([01][0-9]|2[0-3]):[0-5][0-9]$'),
  observing_location  text not null check (char_length(btrim(observing_location)) between 1 and 200),
  duration_hours      double precision not null check (duration_hours >= 0.1 and duration_hours <= 24),

  -- optional coursework fields
  description         text check (char_length(description) <= 2000),
  sky_conditions      text check (char_length(sky_conditions) <= 100),

  -- the group's own extra fields (already captured by the Android app)
  observer_name       text check (char_length(observer_name) <= 80),
  equipment           text check (char_length(equipment) <= 100),
  bortle_scale        smallint check (bortle_scale between 1 and 9),
  seeing_rating       smallint check (seeing_rating between 1 and 5),
  latitude            double precision check (latitude between -90 and 90),
  longitude           double precision check (longitude between -180 and 180),

  created_at          timestamptz not null default now(),
  updated_at          timestamptz not null default now(),
  synced_at           timestamptz not null default now(),   -- last successful upload

  constraint observing_sessions_id_user_key unique (id, user_id),
  constraint observing_sessions_coordinates_pair check ((latitude is null) = (longitude is null))
);

comment on table public.observing_sessions is
  'An astronomy observing session uploaded from the AstroLog Android app.';

-- ---------------------------------------------------------------- celestial_observations

create table public.celestial_observations (
  id                   uuid primary key,   -- generated by the Android app (CelestialObservation.cloudId)
  session_id           uuid not null,
  user_id              uuid not null default auth.uid(),

  -- required coursework fields
  celestial_object     text not null check (char_length(btrim(celestial_object)) between 1 and 120),
  location_in_sky      text not null check (char_length(btrim(location_in_sky)) between 1 and 200),
  observation_details  text not null check (char_length(btrim(observation_details)) between 1 and 4000),

  -- optional coursework field
  additional_comments  text check (char_length(additional_comments) <= 2000),

  -- the group's own extra fields
  object_type          text check (char_length(object_type) <= 60),
  observed_time        text check (observed_time ~ '^([01][0-9]|2[0-3]):[0-5][0-9]$'),
  has_photo            boolean not null default false,       -- photos stay on the phone
  sort_order           integer not null default 0 check (sort_order >= 0),

  created_at           timestamptz not null default now(),
  updated_at           timestamptz not null default now(),

  -- One session has many observations. Deleting a session deletes its observations.
  -- Including user_id in the key guarantees the observation's owner = the session's owner.
  constraint celestial_observations_session_fkey
    foreign key (session_id, user_id)
    references public.observing_sessions (id, user_id)
    on delete cascade
);

comment on table public.celestial_observations is
  'One celestial object seen during an observing session.';

-- ---------------------------------------------------------------- indexes

create index observing_sessions_user_id_idx        on public.observing_sessions (user_id);
create index observing_sessions_session_date_idx   on public.observing_sessions (session_date desc, session_time desc);
create index celestial_observations_session_id_idx on public.celestial_observations (session_id, user_id);
create index celestial_observations_user_id_idx    on public.celestial_observations (user_id);
-- Trigram index: makes case-insensitive partial searches (ILIKE '%jup%') fast.
create index celestial_observations_object_trgm_idx
  on public.celestial_observations using gin (celestial_object extensions.gin_trgm_ops);

-- ---------------------------------------------------------------- updated_at trigger

create or replace function private.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

create trigger profiles_set_updated_at
  before update on public.profiles
  for each row execute function private.set_updated_at();
create trigger observing_sessions_set_updated_at
  before update on public.observing_sessions
  for each row execute function private.set_updated_at();
create trigger celestial_observations_set_updated_at
  before update on public.celestial_observations
  for each row execute function private.set_updated_at();

-- ---------------------------------------------------------------- profile for every auth user

-- SECURITY DEFINER because it writes to public.profiles on behalf of Supabase Auth.
-- It lives in the private schema, so it cannot be called through the REST API.
create or replace function private.sync_profile_from_auth_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, email, display_name)
  values (new.id, new.email, nullif(btrim(new.raw_user_meta_data ->> 'display_name'), ''))
  on conflict (id) do update set email = excluded.email;   -- e.g. anonymous user adds an email later
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function private.sync_profile_from_auth_user();
create trigger on_auth_user_email_changed
  after update of email on auth.users
  for each row execute function private.sync_profile_from_auth_user();

-- Users that already existed before this migration
insert into public.profiles (id, email)
select u.id, u.email from auth.users u
on conflict (id) do nothing;
